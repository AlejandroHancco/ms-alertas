"""
Acceso a PostgreSQL: pool de conexiones, helpers de consulta y esquema.

Conexión por variables de entorno:
  - DATABASE_URL  (ej: postgresql://user:pass@host:5432/dbname?sslmode=require)
  o bien PGHOST PGUSER PGPASSWORD PGDATABASE PGPORT PGSSLMODE
Azure Database for PostgreSQL Flexible Server exige TLS -> sslmode=require por defecto.

Las consultas usan los placeholders nativos de psycopg (%s / %(nombre)s) y las filas
llegan como dict. Para listas: `col = ANY(%s)` con una lista de Python.
"""
import atexit
import datetime
import os
from contextlib import contextmanager

import psycopg
from psycopg.conninfo import make_conninfo
from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool

IntegrityError = psycopg.IntegrityError

# Hora de Perú (GMT-5, sin horario de verano): el servidor en Azure corre en UTC,
# así las fechas de creación/última revisión no se adelantan un día.
LIMA_TZ = datetime.timezone(datetime.timedelta(hours=-5))


def today():
    return datetime.datetime.now(LIMA_TZ).date().isoformat()


def now():
    return datetime.datetime.now(LIMA_TZ).replace(tzinfo=None).isoformat(timespec="seconds")


def _conninfo():
    url = os.environ.get("DATABASE_URL")
    if url:
        return url
    if not os.environ.get("PGHOST"):
        raise RuntimeError(
            "Falta configuración de base de datos. Define DATABASE_URL o "
            "PGHOST/PGUSER/PGPASSWORD/PGDATABASE en las variables de entorno.")
    return make_conninfo(
        host=os.environ["PGHOST"],
        port=os.environ.get("PGPORT", "5432"),
        dbname=os.environ.get("PGDATABASE", "postgres"),
        user=os.environ.get("PGUSER", ""),
        password=os.environ.get("PGPASSWORD", ""),
        sslmode=os.environ.get("PGSSLMODE", "require"))


_pool = None


def pool():
    global _pool
    if _pool is None:
        _pool = ConnectionPool(_conninfo(), min_size=1,
                               max_size=int(os.environ.get("PG_POOL_MAX", "10")),
                               kwargs={"row_factory": dict_row}, open=True)
        atexit.register(close)
    return _pool


def close():
    """Cierra el pool (al terminar scripts o el servidor)."""
    global _pool
    if _pool is not None:
        _pool.close()
        _pool = None


@contextmanager
def tx():
    """Conexión del pool en una transacción: commit al salir, rollback si hay excepción."""
    with pool().connection() as con:
        yield con


def rows(sql, params=None):
    with tx() as con:
        return con.execute(sql, params).fetchall()


def one(sql, params=None):
    with tx() as con:
        return con.execute(sql, params).fetchone()


def scalar(sql, params=None):
    r = one(sql, params)
    return next(iter(r.values())) if r else None


def run(sql, params=None):
    """Ejecuta un INSERT/UPDATE/DELETE y devuelve las filas afectadas."""
    with tx() as con:
        return con.execute(sql, params).rowcount


