def ensure_schema(admin_correo=None):
    """Crea/migra el esquema (idempotente) y garantiza que exista al menos un admin:
    si no hay ninguno se promueve a `admin_correo` o, si no existe, al miembro más antiguo."""
    with tx() as con:
        con.execute("SELECT pg_advisory_xact_lock(84210731)")   # varios workers arrancando a la vez
        for stmt in SCHEMA:
            con.execute(stmt)
        if not con.execute("SELECT 1 FROM miembros WHERE rol='admin'").fetchone():
            row = None
            if admin_correo:
                row = con.execute("SELECT id FROM miembros WHERE correo=%s",
                                  (admin_correo.strip().lower(),)).fetchone()
            row = row or con.execute("SELECT id FROM miembros ORDER BY id LIMIT 1").fetchone()
            if row:
                con.execute("UPDATE miembros SET rol='admin' WHERE id=%s", (row["id"],))
